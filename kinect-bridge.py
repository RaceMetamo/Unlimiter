def import_pykinect():
    """pykinect2 is a 2016 library. Import it with the failure modes named."""
    ver = "%d.%d" % (sys.version_info[0], sys.version_info[1])
    older = ("\n\nThis library is from 2016 and is only really happy on Python 3.8-3.10.\n"
             "You are on %s. If the errors above look like internals rather than\n"
             "anything you did, install Python 3.9 (64-bit) alongside what you have\n"
             "and run the bridge with that:\n"
             "    py -3.9 -m pip install pykinect2 comtypes numpy websockets\n"
             "    py -3.9 kinect-bridge.py" % ver)
    # pykinect2's PyKinectV2.py was generated by comtypes in 2016 and ends with
    # a _check_version() guard that rejects any newer comtypes codegen. The
    # guard is a version stamp, not a compatibility test, so stand it down.
    try:
        import comtypes
        if hasattr(comtypes, "_check_version"):
            comtypes._check_version = lambda *a, **k: None
    except Exception:
        pass
    try:
        from pykinect2 import PyKinectV2
        from pykinect2 import PyKinectRuntime
        return PyKinectV2, PyKinectRuntime
    except AssertionError as e:
        raise SystemExit(
            "pykinect2 failed an internal size assertion: %s\n\n"
            "Known 64-bit bug — a stale struct-size check, harmless to skip.\n"
            "Easiest fix, no file editing, just add -O to skip asserts:\n"
            "    python -O kinect-bridge.py\n\n"
            "Or edit the installed pykinect2/PyKinectV2.py, find\n"
            "    assert sizeof(tagSTATSTG) == 72, sizeof(tagSTATSTG)\n"
            "and change 72 to 80." % e + older)
    except ImportError as e:
        extra = ""
        if "version" in str(e).lower():
            extra = ("\n\nThat is comtypes refusing a module generated by an older\n"
                     "comtypes, not a problem with the sensor. If standing the version\n"
                     "guard down was not enough, pin the old one:\n"
                     "    pip install comtypes==1.1.7\n"
                     "and if it still complains, clear the generated cache:\n"
                     "    python -c \"import comtypes.client, shutil, os; "
                     "shutil.rmtree(os.path.join(os.path.dirname(comtypes.client.__file__),'gen'), ignore_errors=True)\"")
        raise SystemExit(
            "Could not import pykinect2: %s\n\n"
            "Needs the Kinect for Windows SDK 2.0 installed, then:\n"
            "    pip install pykinect2 comtypes\n"
            "Meanwhile --simulate proves the whole browser side without it."
            % e + extra + older)
    except Exception as e:
        raise SystemExit(
            "pykinect2 failed to load: %s: %s" % (type(e).__name__, e) + older)


class KinectSource:
    """Polls a Kinect v2 through pykinect2 / Kinect for Windows SDK 2.0."""

    def __init__(self):
        PyKinectV2, PyKinectRuntime = import_pykinect()

        if not hasattr(time, "clock"):
            time.clock = time.perf_counter
        flags = (PyKinectV2.FrameSourceTypes_Depth |
                 PyKinectV2.FrameSourceTypes_BodyIndex)
        self.rt = PyKinectRuntime.PyKinectRuntime(flags)

        # give the runtime a moment to bring the sensor up
        t0 = time.time()
        while self.rt.depth_frame_desc.Width == 0 and time.time() - t0 < 5:
            time.sleep(0.1)

        self.width = int(self.rt.depth_frame_desc.Width) or 512
        self.height = int(self.rt.depth_frame_desc.Height) or 424
        self.min_mm = 500
        self.max_mm = 4500
        self._depth = np.zeros(self.width * self.height, np.uint16)
        self._body = np.full(self.width * self.height, NO_BODY, np.uint8)
        print("Kinect v2 online: %dx%d" % (self.width, self.height))

    def read(self):
        """Returns (depth uint16[], body uint8[], got_new)."""
        got = False
        if self.rt.has_new_depth_frame():
            d = self.rt.get_last_depth_frame()
            if d is not None:
                self._depth = np.asarray(d, np.uint16).reshape(-1)
                got = True
        if self.rt.has_new_body_index_frame():
            b = self.rt.get_last_body_index_frame()
            if b is not None:
                self._body = np.asarray(b, np.uint8).reshape(-1)
                got = True
        return self._depth, self._body, got

    def close(self):
        try:
            self.rt.close()
        except Exception:
            pass


